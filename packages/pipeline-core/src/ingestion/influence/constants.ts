/**
 * Get all actors of a specific category.
 */
export function getActorsByCategory(category: InfluenceActorCategory): InfluenceActor[] {
  return TRACKED_INFLUENCE_ACTORS.filter(a => a.category === category);
}

/**
 * Get all actors with a specific priority.
 */
export function getActorsByPriority(priority: InfluencePriority): InfluenceActor[] {
  return TRACKED_INFLUENCE_ACTORS.filter(a => a.priority === priority);
}

/**
 * Find an actor by name (partial match).
 */
export function findInfluenceActor(query: string): InfluenceActor | null {
  const q = query.toLowerCase();
  return TRACKED_INFLUENCE_ACTORS.find(a =>
    a.name.toLowerCase().includes(q) ||
    a.aliases.some(alias => alias.toLowerCase().includes(q)),
  ) ?? null;
}
