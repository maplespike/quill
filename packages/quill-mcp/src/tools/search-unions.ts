import type { ToolDefinition, ToolHandler } from './types.js';
import { searchCkan } from './upstream-fetcher.js';

export const definition: ToolDefinition = {
  name: 'search_unions',
  description:
    'Search Canadian labour union data — collective agreements, membership statistics, ' +
    'and labour organization information across federal and provincial jurisdictions.',
  inputSchema: {
    type: 'object',
    properties: {
      query: {
        type: 'string',
        maxLength: 2000,
        description: 'Search terms — union name, sector, or province (e.g., "CUPE Ontario", "teachers union", "public sector")',
      },
      limit: {
        type: 'number',
        description: 'Max results to return (default 20)',
      },
    },
    required: ['query'],
  },
};

export const handler: ToolHandler = async (args: Record<string, unknown>) => {
  const query = String(args.query ?? '');
  const limit = Number(args.limit ?? 20);
  if (!query.trim()) return { content: { tool: 'search_unions', query: '', error: 'No search query provided.' }, isError: true };
  try {
    const result = await searchCkan(query, limit);
    return { content: { tool: 'search_unions', query, limit, ...result } };
  } catch (err) {
    return { content: { tool: 'search_unions', query, error: err instanceof Error ? err.message : 'Unknown error' }, isError: true };
  }
};
