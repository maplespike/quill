#!/usr/bin/env bash
# Quill Cluster Health Monitor
# Checks cluster state and creates GitHub issues for problems.
# Usage: quill-health-check.sh [--create-issue]
set -euo pipefail

REPO="reverb256/quill"
ISSUES=""

check_node() {
  local node="$1"
  local status
  status=$(kubectl get node "$node" -o jsonpath='{.status.conditions[?(@.type=="Ready")].status}' 2>/dev/null || echo "Unknown")
  if [ "$status" != "True" ]; then
    ISSUES="${ISSUES}Node NotReady: $node (status=$status)
"
  fi
}

check_pod() {
  local ns="$1"
  local pod_status
  pod_status=$(kubectl get pods -n "$ns" --no-headers 2>/dev/null || echo "unreachable")
  if echo "$pod_status" | grep -vq "Running\|Completed"; then
    local bad
    bad=$(echo "$pod_status" | grep -v "Running\|Completed" | awk '{print $1, $3}' | head -5)
    ISSUES="${ISSUES}Non-running pods in $ns: $bad
"
  fi
}

check_http() {
  local url="$1"
  local label="$2"
  if ! curl -sf --connect-timeout 5 "$url" > /dev/null 2>&1; then
    ISSUES="${ISSUES}Unreachable: $label ($url)
"
  fi
}

# Node health (must be on zephyr or a node with kubectl access)
check_node "zephyr" || true
check_node "forge" || true
check_node "nexus" || true
check_node "sentry" || true

# Pod health
check_pod "maplespike" || true
check_pod "ai-inference" || true
check_pod "monitoring" || true

# HTTP endpoints (on-cluster)
check_http "http://sentry:8001/health" "AI inference (sentry:8001)" || true
check_http "http://forge:8002/health" "AI inference (forge:8002)" || true

# Public endpoints
check_http "https://quill.maplespike.ca/" "Public portal" || true

# Output
if [ -n "$ISSUES" ]; then
  TIMESTAMP=$(date -u +"%Y-%m-%dT%H:%M:%SZ")
  echo "has_issues=true"
  echo "issues<<ENDISSUES"
  echo "$ISSUES"
  echo "ENDISSUES"

  # Create/update GitHub issue if --create-issue flag
  if [ "${1:-}" = "--create-issue" ]; then
    BODY="## Cluster Health Issues

Detected at: $TIMESTAMP

### Issues
\`\`\`
$ISSUES
\`\`\`

### Next Steps
- Check \`kubectl describe node <name>\` for node issues
- Restart: \`kubectl rollout restart deployment -n maplespike --all\`
- Full deploy: \`cd /etc/nixos && colmena deploy\`

---
_🤖 Auto-generated by health-monitor_"

    # Check for existing open issue
    EXISTING=$(gh issue list --repo "$REPO" --label infrastructure --state open --json number --jq '.[0].number' 2>/dev/null || echo "")

    if [ -n "$EXISTING" ]; then
      gh issue comment "$EXISTING" --repo "$REPO" --body "Updated $TIMESTAMP"
      gh issue edit "$EXISTING" --repo "$REPO" --body "$BODY" 2>/dev/null || true
      echo "Updated existing issue #$EXISTING"
    else
      gh issue create \
        --repo "$REPO" \
        --title "fix: Cluster Health Issues Detected" \
        --label "infrastructure,bug,p1,auto-generated" \
        --body "$BODY"
    fi
  fi
else
  echo "has_issues=false"
  echo "issues=Cluster healthy"
fi
