#!/usr/bin/env bash
# =============================================================================
# wire-lan-dns-unbound.sh — Unbound local-zone for *.maplespike.lan
# =============================================================================
# Requires bash 4+ (uses `declare -A` for the per-host IP map). Default bash
# on most Linux distros (incl. k3s host / homelab nodes) is 4+. Default bash
# on macOS is 3.2 — if you need to dry-run there, swap to parallel arrays.
# Writes an Unbound local-data zone that resolves every `*.maplespike.lan`
# hostname to the k3s Traefik ingress IP, then reloads Unbound.
#
# Usage:
#   sudo ./wire-lan-dns-unbound.sh 192.0.2.10                     # ingress IP (required)
#   sudo ./wire-lan-dns-unbound.sh 192.0.2.10 /etc/unbound/conf.d
#
# NixOS users: instead of running this script, drop the contents of
# `local-zone.conf` into `services.unbound.extraConfig`, OR add:
#   services.unbound.extraConfig += builtins.readFile ./local-zone.conf;
# to your Nix flake's `nixosModules.<host>.config`.
#
# Prereqs:
#   - unbound installed locally (systemd unit: unbound.service)
#   - /etc/unbound/conf.d/* already included by /etc/unbound/unbound.conf
#     (the Debian/Ubuntu/Alpine packages do this by default)
# =============================================================================

set -euo pipefail

# No default: a wrong guess points every *.maplespike.lan host at nothing.
INGRESS_IP="${1:?usage: wire-lan-dns-unbound.sh <ingress-ip> [conf-dir]}"
CONF_DIR="${2:-/etc/unbound/conf.d}"
ZONE_FILE="$CONF_DIR/maplespike-lan.conf"

# Hosts to publish — keep aligned with maplespike/k8s/base/15-ingress-lan.yaml
# (Ingress `tls.hosts` list) and maplespike/k8s/base/16-cert-issuer-lan.yaml's
# ClusterIssuer URL (`step-ca.maplespike.lan`).
HOSTS=(
  maplespike.lan
  portal.maplespike.lan
  api.maplespike.lan
  mcp.maplespike.lan
  dev.maplespike.lan
  dev-api.maplespike.lan
  dev-mcp.maplespike.lan
  # step-ca.maplespike.lan is referenced by the cert-manager ClusterIssuer.
  # Resolves to STEP_CA_IP (defaults to INGRESS_IP) so cert-manager can reach
  # step-ca whether step-ca runs on the k3s ingress node OR a separate
  # homelab host with its own LAN address.
  step-ca.maplespike.lan
)

# Per-host IP mapping for the local-data zone. Override STEP_CA_IP env var
# when step-ca runs on a homelab box with a different LAN address.
declare -A HOST_TO_IP=(
  ["maplespike.lan"]=$INGRESS_IP
  ["portal.maplespike.lan"]=$INGRESS_IP
  ["api.maplespike.lan"]=$INGRESS_IP
  ["mcp.maplespike.lan"]=$INGRESS_IP
  ["dev.maplespike.lan"]=$INGRESS_IP
  ["dev-api.maplespike.lan"]=$INGRESS_IP
  ["dev-mcp.maplespike.lan"]=$INGRESS_IP
  ["step-ca.maplespike.lan"]=${STEP_CA_IP:-$INGRESS_IP}
)

log()  { printf '\033[1;34m[wire-dns]\033[0m %s\n' "$*"; }
err()  { printf '\033[1;31m[wire-dns]\033[0m %s\n' "$*" >&2; }
SUDO=""
[[ $EUID -eq 0 ]] || SUDO="sudo"

# --- root check ---
if [[ $EUID -ne 0 ]]; then
  err "must run as root (or with sudo) — needs to write under $CONF_DIR"
  exit 1
fi

# --- unbound binary check ---
if ! command -v unbound >/dev/null 2>&1 && ! command -v unbound-checkconf >/dev/null 2>&1; then
  err "no unbound binary on PATH. This script targets a local Unbound resolver;"
  err "for remote resolvers, copy local-zone.conf to that host's conf.d/."
  exit 1
fi

# --- write zone file ---
mkdir -p "$CONF_DIR"
log "writing $ZONE_FILE (resolves ${#HOSTS[@]} *.maplespike.lan hosts → $INGRESS_IP)"
{
  echo '# Auto-generated by maplespike/scripts/wire-lan-dns-unbound.sh'
  echo '# Re-runs overwrite. Edit the IP argument to the script to change.'
  echo '# Hosts listed here are kept aligned with'
  echo '#   maplespike/k8s/base/15-ingress-lan.yaml (Ingress tls.hosts).'
  echo 'server:'
for h in "${HOSTS[@]}"; do
  ip="${HOST_TO_IP[$h]:-$INGRESS_IP}"   # defensive fallback if a host is missing from the map
  # local-data guards the zone against any upstream caching.
  echo "    local-zone: \"$h.\" static"
  echo "    local-data: \"$h. 3600 IN A $ip\""
done
} > "$ZONE_FILE"

# --- sanity-check include directive ---
# We use fixed-string grep to avoid regex quote-juggling. The full unbound
# directive grammar varies across distros (some emit `include: "..."`,
# others `include: ".../*.conf"`), so we only check that the conf-dir path
# is referenced at all. If it isn't, print the canonical include snippet.
if [[ -f /etc/unbound/unbound.conf ]] && grep -qF "$CONF_DIR" /etc/unbound/unbound.conf; then
  log "/etc/unbound/unbound.conf references $CONF_DIR — good."
else
  err "ATTENTION: $ZONE_FILE was written, but /etc/unbound/unbound.conf does"
  err "not reference $CONF_DIR. Ensure the server: block contains:"
  err "    include: \"$CONF_DIR/*.conf\""
  err "Then reload with:   $SUDO systemctl reload unbound"
fi

# --- reload (best effort) ---
if command -v unbound-control >/dev/null 2>&1; then
  if $SUDO unbound-control reload 2>/dev/null; then
    log "unbound reloaded via unbound-control"
  else
    err "unbound-control reload failed; restart manually"
  fi
elif command -v systemctl >/dev/null 2>&1; then
  if $SUDO systemctl reload unbound 2>/dev/null; then
    log "unbound reloaded via systemctl"
  elif $SUDO systemctl restart unbound 2>/dev/null; then
    log "unbound restarted"
  else
    err "could not reload/restart unbound — restart it manually after editing"
  fi
fi

echo
log "verify with:"
echo "    dig +short maplespike.lan @$INGRESS_IP"
echo "    dig +short api.maplespike.lan @$INGRESS_IP"
echo "    curl -kI https://api.maplespike.lan/v1/health"
